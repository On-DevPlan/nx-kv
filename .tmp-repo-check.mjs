import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = mkdtempSync(join(tmpdir(), 'nxkv-repo-att-'));
process.env.NX_KV_HOME = join(root, 'home');
process.env.NX_KV_DB = join(root, 'db.sqlite');
const cwd = 'D:/a_js/js_proj/nx-kv';
const repos = await import('./src/modules/repos/service.js');
await repos.addRepo({ path: cwd, key: 'demo/self', type: 'dev', name: 'nx-kv-self' });
const lt = await import('./src/modules/localtask/service.js');
const ops = await import('./src/modules/localtask/ops/attach.js');
const { task } = await lt.addTask({ cwd, text: '# 测试 repo 附件\n\n正文' });
const r = await ops.attachToTask({ id: task.id, cwd, repo: 'demo/self', noEmbed: true });
console.log('ATTACH', JSON.stringify({ kind: r.kind, fileId: r.fileId }));
const show = await ops.listTaskAttachments({ cwd, id: task.id });
const list = show.attachments || show.list || [];
const hit = list.find((a) => a.kind === 'repo');
console.log('RES', JSON.stringify({ kind: hit?.kind, key: hit?.repoKey, path: hit?.localPath, exists: hit?.exists, missing: hit?.missing, docs: hit?.docCount, usage: (hit?.usage || '').slice(0, 120) }));
const { attachTemplateCtx, attachmentInstruction } = await import('./src/modules/localtask/ops/attach-template.js');
const ctx = attachTemplateCtx(list).attach;
const item = ctx.list.find((x) => x.kind === 'repo');
console.log('CTX', JSON.stringify({ mandatory: item?.mandatory, hasMandatory: ctx.hasMandatory, mandatoryCount: ctx.mandatoryCount, access: (item?.access || '').slice(0, 100), repoLocalPath: item?.repo?.localPath, repoCmd: item?.repo?.cmd }));
const ins = attachmentInstruction(list);
console.log('HAS_MUST', /必须访问/.test(ins), '| HAS_FORBID', /禁止凭记忆臆测/.test(ins), '| HAS_REPO_PATH', ins.includes(cwd.replace(/\\/g, '\\')) || ins.includes('D:/a_js/js_proj/nx-kv'));
console.log('--- instruction 片段 ---');
console.log(ins.split('\n').slice(0, 12).join('\n'));
process.exit(0);
